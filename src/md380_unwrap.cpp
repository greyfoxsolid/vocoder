// Reads wrapped_path (the MD-380-D2.32(AD).bin OEM image), writes the unwrapped
// application image (D002.032.bin) to unwrapped_path. Returns a qdv_status.
int qdv_unwrap_md380_impl(const char* wrapped_path, const char* unwrapped_path) {
    FILE* f = fopen(wrapped_path, "rb");
    if (!f) return QDV_ERR_UNWRAP_OPEN;
    fseek(f, 0, SEEK_END);
    long wlen = ftell(f);
    fseek(f, 0, SEEK_SET);
    if (wlen < 512) { fclose(f); return QDV_ERR_UNWRAP_FORMAT; }
    std::vector<unsigned char> img((size_t)wlen);
    size_t got = fread(img.data(), 1, (size_t)wlen, f);
    fclose(f);
    if (got != (size_t)wlen) return QDV_ERR_UNWRAP_OPEN;

    // Header: magic "OutSecurityBin" @0; start u32le @128; app_len u32le @132.
    if (memcmp(img.data(), "OutSecurityBin", 14) != 0) return QDV_ERR_UNWRAP_FORMAT;
    uint32_t start =
        img[128] | (img[129] << 8) | (img[130] << 16) | ((uint32_t)img[131] << 24);
    uint32_t app_len =
        img[132] | (img[133] << 8) | (img[134] << 16) | ((uint32_t)img[135] << 24);
    // Sanity: app image sits in flash window, app_len == file - 512 (hdr+footer).
    if (start < 0x8000000u || start >= 0x8200000u) return QDV_ERR_UNWRAP_FORMAT;
    if ((uint64_t)app_len != (uint64_t)wlen - 512u) return QDV_ERR_UNWRAP_FORMAT;
    if (256u + (uint64_t)app_len > (uint64_t)wlen) return QDV_ERR_UNWRAP_FORMAT;

    // app = XOR(img[256 : 256+app_len], key) with the key cycling.
    std::vector<unsigned char> app(app_len);
    const size_t klen = sizeof(kMd380Key);
    for (uint32_t i = 0; i < app_len; i++)
        app[i] = img[256 + i] ^ kMd380Key[i % klen];

    FILE* o = fopen(unwrapped_path, "wb");
    if (!o) return QDV_ERR_UNWRAP_WRITE;
    size_t wr = fwrite(app.data(), 1, app.size(), o);
    fclose(o);
    if (wr != app.size()) return QDV_ERR_UNWRAP_WRITE;
    return QDV_OK;
}
